-- 改期申请开关。
--
-- 背景：排期定下来之后，改期申请还在陆续进来（本届最晚一条距面试只剩 42 小时），
-- 而每条都要人工重排。管理员需要一个「到此为止」的闸门，否则只能一条条手动拒绝，
-- 学生那边还以为申请有戏、白等。
--
-- 做成开关而不是截止时间：管理员的真实需求是「我现在不想再收了」，这是一个当下的
-- 决定，不是一个能提前算准的时刻。截止时间以后想要可以再叠一层，开关是底座。
--
-- 默认 1（开）——不配置就是现在的行为，老周期不受影响。
ALTER TABLE `recruitment_cycle`
    ADD COLUMN `reschedule_open` TINYINT NOT NULL DEFAULT 1
        COMMENT '是否接受改期申请：1=接受(默认) 0=已关闭' AFTER `online_meeting_link`;
